// Regenerates src/content/mediaManifest.ts: every built-in image/video the site uses,
// so the editor can list them in "Images & Videos". Run: node scripts/media-manifest.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = "src";
const SKIP = [join("src", "sanity"), join("src", "content", "mediaManifest.ts"), join("src", "app", "opengraph-image.tsx")];
const RE = /["'`]((?:\/(?:images|video|client logo)\/[^"'`?]+\.(?:webp|png|jpe?g|svg|gif|avif|mp4|webm))|(?:https:\/\/images\.unsplash\.com\/[^"'`]+))["'`]/g;

const AREA = [
  [/PiximLogo|Navbar|Footer/, "Logo"],
  [/HeroSection|VideoShowcase|homeData|content\/home/, "Home page"],
  [/StatsBar|FreeConsultation|BrandStories|RecentWork|LogoCarousel|ReadyForLogo/, "Home page"],
  [/caseStudies|ProjectsView|PortfolioSection/, "Projects page / case studies"],
  [/serviceProjects|service-landing/, "Service pages"],
  [/about\/|AboutView/, "About page"],
  [/agencyData|GsapReviews/, "Reviews & portfolio"],
  [/studioContent|ServicesView|PricingView/, "Services / Pricing pages"],
];

const found = new Map();
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (SKIP.some((s) => p.startsWith(s))) continue;
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(name)) {
      const text = readFileSync(p, "utf8");
      for (const m of text.matchAll(RE)) {
        const src = m[1];
        if (!found.has(src)) found.set(src, new Set());
        found.get(src).add(relative(ROOT, p));
      }
    }
  }
}
walk(ROOT);

const items = [...found.entries()]
  .map(([src, files]) => {
    const where = [...files];
    const areas = [...new Set(where.map((f) => AREA.find(([re]) => re.test(f))?.[1] ?? "Other"))];
    const area = areas.join(", ");
    const isVideo = /\.(mp4|webm)$/.test(src);
    const name = src.startsWith("http") ? `Stock photo ${src.match(/photo-([\w-]+)/)?.[1]?.slice(0, 10) ?? ""}` : decodeURIComponent(src.split("/").pop());
    return { src, name, area, type: isVideo ? "video" : "image" };
  })
  .sort((a, b) => a.area.localeCompare(b.area) || a.name.localeCompare(b.name));

const out = `// AUTO-GENERATED by scripts/media-manifest.mjs – every built-in image/video on the site.
// Used by the editor's "Images & Videos" list. Re-run the script after adding new images to the code.

export interface MediaItem {
  src: string;
  name: string;
  area: string;
  type: "image" | "video";
}

export const MEDIA_MANIFEST: MediaItem[] = ${JSON.stringify(items, null, 2)};
`;
writeFileSync(join(ROOT, "content", "mediaManifest.ts"), out);
console.log(`${items.length} media files listed`);
