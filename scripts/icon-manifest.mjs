// Regenerates the replaceable-icon list:
//  - src/content/lucide.tsx      every lucide icon the site uses, wrapped so it can be replaced from the editor
//  - src/content/iconManifest.ts the list shown in the editor under "Icons"
// Run after adding a new icon to the code: node scripts/icon-manifest.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { AREA_RULES, areaFor } from "./areas.mjs";

const ROOT = "src";
const SKIP = [join("src", "sanity"), join("src", "content", "lucide.tsx"), join("src", "content", "icons.tsx")];
const IMPORT_RE = /import\s+(type\s+)?\{([^}]+)\}\s+from\s+["'](?:lucide-react|@\/content\/lucide)["']/g;
const TYPES = new Set(["LucideIcon", "LucideProps"]);

const used = new Map(); // icon name -> Set(files)
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (SKIP.some((s) => p.startsWith(s))) continue;
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.tsx?$/.test(name)) {
      const text = readFileSync(p, "utf8");
      for (const m of text.matchAll(IMPORT_RE)) {
        if (m[1]) continue;
        for (const spec of m[2].split(",")) {
          const clean = spec.trim().replace(/^type\s+/, "");
          if (!clean || spec.trim().startsWith("type ")) continue;
          const icon = clean.split(/\s+as\s+/)[0].trim();
          if (TYPES.has(icon)) continue;
          if (!used.has(icon)) used.set(icon, new Set());
          used.get(icon).add(relative(ROOT, p));
        }
      }
    }
  }
}
walk(ROOT);

const icons = [...used.keys()].sort();
const humanize = (n) => n.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/([A-Z])([A-Z][a-z])/g, "$1 $2");

writeFileSync(
  join(ROOT, "content", "lucide.tsx"),
  `"use client";

// AUTO-GENERATED by scripts/icon-manifest.mjs – do not edit by hand.
// Every line icon used on the site, wrapped so it can be replaced in the editor ("Icons").
// Import icons from "@/content/lucide" instead of "lucide-react".

import {
${icons.map((i) => `  ${i} as L_${i},`).join("\n")}
} from "lucide-react";
import { iconSlot } from "./icons";

export type { LucideIcon, LucideProps } from "lucide-react";

${icons.map((i) => `export const ${i} = iconSlot("lucide:${i}", L_${i});`).join("\n")}
`
);

const SOCIAL = [
  ["facebook", "Facebook"],
  ["instagram", "Instagram"],
  ["linkedin", "LinkedIn"],
  ["behance", "Behance"],
  ["x", "X (Twitter)"],
  ["youtube", "YouTube"],
  ["whatsapp", "WhatsApp"],
];
const SERVICES = [
  ["logo-design", "Logo & Brand Identity"],
  ["social-media", "Social Media Design"],
  ["package-design", "Package & Label Design"],
  ["motion-video", "Motion Graphics & Video"],
  ["digital-marketing", "Digital Marketing & Ads"],
  ["web-design", "Website Design & Development"],
  ["seo-growth", "SEO & Growth"],
];

const items = [
  ...SERVICES.map(([id, label]) => ({ key: `service:${id}`, name: `${label} – service icon`, area: "Service icons (menu, service cards)", kind: "service" })),
  ...SOCIAL.map(([id, label]) => ({ key: `social:${id}`, name: `${label} icon`, area: "Social media icons", kind: "social" })),
  ...icons.map((i) => {
    const areas = [...new Set([...used.get(i)].map(areaFor))];
    return { key: `lucide:${i}`, name: humanize(i), area: areas.join(", "), kind: "lucide" };
  }),
];

writeFileSync(
  join(ROOT, "content", "iconManifest.ts"),
  `// AUTO-GENERATED by scripts/icon-manifest.mjs – every replaceable icon on the site.
// Used by the editor's "Icons" list. Re-run the script after adding new icons to the code.

export interface IconItem {
  key: string;
  name: string;
  area: string;
  kind: "lucide" | "social" | "service";
}

export const ICON_MANIFEST: IconItem[] = ${JSON.stringify(items, null, 2)};
`
);
console.log(`${items.length} icons listed (${icons.length} line icons)`);
void AREA_RULES;
