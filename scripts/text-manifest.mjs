// Regenerates src/content/textManifest.ts: every small text on the site written as
// tx("key", "Default text") (or <Tx k="key" d="Default text" />), grouped by page,
// so the editor can list it under "Website text". Run: node scripts/text-manifest.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { AREAS, areaInfo } from "./areas.mjs";

const ROOT = "src";
const SKIP = [join("src", "sanity"), join("src", "content")];
const STR = String.raw`"(?:[^"\\]|\\.)*"`;
const CALL = new RegExp(String.raw`\btx\(\s*(${STR})\s*,\s*(${STR})\s*\)`, "g");
const EL = new RegExp(String.raw`<Tx\s+k=(${STR})\s+d=(${STR})\s*\/>`, "g");

const found = new Map(); // key -> { text, files:Set }
function add(key, text, file) {
  const prev = found.get(key);
  if (prev && prev.text !== text) {
    console.warn(`⚠ key "${key}" has two different default texts – keeping the first`);
    prev.files.add(file);
    return;
  }
  if (prev) prev.files.add(file);
  else found.set(key, { text, files: new Set([file]) });
}

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (SKIP.some((s) => p.startsWith(s))) continue;
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.tsx?$/.test(name)) {
      const text = readFileSync(p, "utf8");
      const rel = relative(ROOT, p);
      for (const m of text.matchAll(CALL)) add(JSON.parse(m[1]), JSON.parse(m[2]), rel);
      for (const m of text.matchAll(EL)) add(JSON.parse(m[1]), JSON.parse(m[2]), rel);
    }
  }
}
walk(ROOT);

const order = new Map(AREAS.map((a, i) => [a.id, i]));
const items = [...found.entries()].map(([key, { text, files }]) => {
  const info = areaInfo([...files][0]);
  const section = key.split(".")[0].split("/").pop().replace(/([a-z])([A-Z])/g, "$1 $2").replace(/[-_]/g, " ");
  return { key, text, area: info.id, section };
});
// keep source order inside each page, pages in display order
items.sort((a, b) => order.get(a.area) - order.get(b.area));

const out = `// AUTO-GENERATED by scripts/text-manifest.mjs – every small editable text on the site.
// Used by the editor's "Website text" pages. Re-run the script after adding tx() texts to the code.

export interface TextItem {
  key: string;
  text: string;
  area: string;
  section: string;
}

export const TEXT_AREAS = ${JSON.stringify(AREAS.filter((a) => items.some((i) => i.area === a.id)), null, 2)};

export const TEXT_MANIFEST: TextItem[] = ${JSON.stringify(items, null, 2)};
`;
writeFileSync(join(ROOT, "content", "textManifest.ts"), out);
console.log(`${items.length} texts listed in ${new Set(items.map((i) => i.area)).size} pages`);
